import streamlit as st
import time

# पेज की सेटिंग्स
st.set_page_config(page_title="Happy Birthday!", page_icon="🎂", layout="centered")

# मुख्य हेडिंग
st.title("🎉 Happy Birthday to You! 🎂")

# 1. यहाँ से आप चुन सकते हैं कि किसका बर्थडे है
friend = st.radio("किसका जन्मदिन है? चुनें 👇", ["Dear Kanha", "Dear Ashad"])

# विश करने वाले का नाम (यहाँ Deepak नाम पहले से सेट कर दिया है)
wisher_name = st.text_input("अपना (विश करने वाले का) नाम यहाँ लिखें:", value="Deepak")

# बटन जिसपर क्लिक करते ही जादू होगा
if st.button("स्पेशल बर्थडे विश देखने के लिए यहाँ क्लिक करें! ✨"):
    
    # 1. स्क्रीन पर रंग-बिरंगे गुब्बारे उड़ाने के लिए
    st.balloons()
    
    # 2. सस्पेंस बनाने के लिए छोटा सा लोडिंग इफेक्ट
    with st.spinner('आपके लिए सरप्राइज लोड हो रहा है...'):
        time.sleep(1.5)
    
    # 3. बधाई संदेश (बड़े अक्षरों में)
    st.success(f"✨ जनमदिन की बहुत-बहुत शुभकामनाएँ, {friend}! ✨")
    
    # 4. अगर 'Dear Kanha' चुना है तो उनके लिए अलग शायरी
    if friend == "Dear Kanha":
        st.markdown(f"""
### 🎈 भगवान करे आपका यह साल खुशियों से भरा हो! 🎈

> *"फूलों ने अमृत का जाम भेजा है,🌸*  
> *सूरज ने गगन से सलाम भेजा है,*🌞  
> *मुबारक हो आपको आपका जन्मदिन,*🎂  
> *हमने दिल से ये पैगाम भेजा है!"*❤️

---
**From (आपकी तरफ से):**  
👉 *{wisher_name}*
        """)
        
    # 5. अगर 'Dear Ashad' चुना है तो उनके लिए अलग शायरी
    elif friend == "Dear Ashad":
        st.markdown(f"""
### 🎈 भगवान करे आपका यह खास दिन बहुत शानदार हो! 🎈

> *"तमाम खुशियाँ मिले आपको इस जहाँ में,🌟*  
> *हर पल मुस्कान रहे आपके होठों पे,*😊  
> *दुआ है हमारी बस यही दिल से,*❤️  
> *सलामत रहें आप जिंदगी के हर मोड़ पे!"*✨

---
**From (आपकी तरफ से):**  
👉 *{wisher_name}*
        """)
        
    # 6. उत्सव जैसा फील देने के लिए पटाखे (Snow effect)
    st.snow()

